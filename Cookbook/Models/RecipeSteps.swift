import Foundation
/// A single record in the `collection of recipe steps`
/// - parameter recipeID : **First half of Primary key**,  identifies the recipe
/// - parameter rowID : **Second half of Primary key**, identifies the row in the recipe
/// - parameter itemCode : The `id` of the ingredient used
/// - parameter quantity : The amount required for this step
/// - parameter actions : An instruction for this step. May be a comment for an ingredient.
/// - parameter isAction : A flag to determine if stp is an instruction(`true`) or ingredient(`false`).
struct RecipeStep:Identifiable,Hashable,Equatable{
    var recipeID:Int = -1 //Key 1st half
    var rowID:Int = 0     //Key 2nd half
    var itemCode:Int = 0   //
    var quantity:Double = 0.0
    var actions:String
    var isAction:Bool = false
    
    /// **Primary Key** A unique ID for search operations, combining `recipeID` and `rowID`.
    var id:Int{recipeID * 1000 + rowID}
    
    /// A blank `RecipeStep` to use when initializing variables.
    static var blank:RecipeStep{RecipeStep(actions:"")}
}

@Observable
class RecipeSteps{
    
