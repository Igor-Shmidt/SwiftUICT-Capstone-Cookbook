//----- Add Methods
    
    /// Find the next ID available for a recipe row
    /// - Returns one greater than the largest ID
    func nextRowID(recipeID:Int)->Int{
        let steps = allSteps(for: recipeID)
        if let lastStep = steps.max(by: {$0.rowID < $1.rowID}){
            return lastStep.rowID + 1
        } else {
            return 0
        }
    }
    
    /// Add the row with a `RecipeStep`
    func addRow(recipeStep:RecipeStep){
        var recipeStep = recipeStep                      //make mutable copy
        recipeStep.rowID = nextRowID(recipeID: recipeStep.recipeID) //assign the correct row ID
        table.append(recipeStep)                        // Append the row
    }
    
    /// Add the row specifying properties.
    /// - if `rowID` is `nil` or omitted, will generate a `rowID`
    func addRow(recipeID:Int,rowID:Int! = nil,itemCode:Int,quantity:Double,actions:String,isAction:Bool){
        print("in row!")
        // create a new mutable row from the arguments, if row is nil set to 0
        var newRow:RecipeStep = RecipeStep(recipeID: recipeID, rowID: rowID ?? 0, itemCode: itemCode, quantity: quantity, actions: actions,isAction: isAction)
        print(newRow)
        //find the correct row ID for this.
        // nil row indicates making a new row
        if let rowID = rowID{ //explicit row creation. if row exists add to end.
            if rowExists(for:recipeID,row:rowID){
                // row exists, so replace the row and return
                updateRow(recipeStep:newRow)
                return
            }else{
                // row does not exist(i.e. out of bounds) -- set `rowID` to append the row
                newRow.rowID = nextRowID(recipeID: recipeID)
            }
        } else {
            // New row, so append the row.
            newRow.rowID = nextRowID(recipeID: recipeID)
        }
        //append the row.
        table.append(newRow)
    }
    
 //----- Delete Methods
    ///Delete based on an `id`
    func removeRow(rowID:Int){
        // find the index of the item with id, and remove from that index.
        if let index = table.firstIndex(where: {$0.id == rowID}){
            table.remove(at: index)
        }
    }
    /// Cleans up aftere deletion of a recipe to prevent orphan entries
    func removeRecipeSteps(for recipeID:Int){
        table.removeAll(where: {$0.recipeID == recipeID})
    }
    
    
//----- Update methods
    
    /// Update based on a `recipeStep`
    func updateRow(recipeStep:RecipeStep){
        //find the index of that id, and replace the element at that index.
        if let index = table.firstIndex(where: {$0.id == recipeStep.id}){
            print("Index is",index)
            print(recipeStep)
            table[index] = recipeStep
        }
    }
    
//----- Insert methods
    ///Inserts a row after a specified row, updating the `rowID` property to keep in sequence
    /// - parameter after: a selected  `RecipeStep` to place a new row after. also specifies the recipe involoved.
    /// - parameter with: a new `RecipeStep` to insert. `RecipeID` and `RowID` are generated by this method, and are therefore not siginifant in the argument.
    func insertRow(after baseRow:RecipeStep,with insertedRow:RecipeStep){
        // if the base row exists
        if let baseIndex = table.firstIndex(where: {$0.recipeID == baseRow.recipeID && $0.rowID == baseRow.rowID }){
                // Make space for the new row in the `rowIDs`
                for index in table.startIndex..<table.endIndex{
                    if table[index].recipeID == baseRow.recipeID && table[index].rowID > baseRow.rowID{
                        table[index].rowID += 1
                    }
                }
                // make a mutable row, and change the keys for insertion
                var newRow = insertedRow
                newRow.recipeID = baseRow.recipeID
                newRow.rowID = baseRow.rowID + 1
                // do the insertion
                let newIndex = baseIndex + 1
                table.insert(newRow, at: newIndex)
            } else {
                print("No changes made")
            }
        }
    
    
//----- Find methods
    
    ///Return an step by its `id`
    func step(id:Int)->RecipeStep!{
        table.first{$0.id == id}
    }
    
    //return the index of a row
        func findRowIndex(id:Int)->Int!{
            table.firstIndex{$0.id == id}
        }
    
    ///Return an step by its `recipeID` and `row`
    func step(recipeID:Int,row:Int)->RecipeStep!{
        table.first{$0.recipeID == recipeID && $0.rowID == row}
    }
    
    ///Find all steps by `recipeID`
    func allSteps(for recipeID:Int )->[RecipeStep]{
        table.filter{$0.recipeID == recipeID}
    }
    ///Find all ingredient steps
    func ingredientSteps(for recipeID:Int )->[RecipeStep]{
        table.filter{$0.recipeID == recipeID && !$0.isAction}
    }
    /// Find all action steps
    func actionSteps(for recipeID:Int )->[RecipeStep]{
        table.filter{$0.recipeID == recipeID && $0.isAction}
    }
    
    /// Find if a row exists
    func rowExists(for recipeID:Int, row:Int)->Bool{
        table.contains(where:{$0.recipeID == recipeID && $0.rowID == row})
    }
    
//---- Error checking
    /// find if there are duplicate records
    /// - returns an array of `ids` indiciating the recipe and row duplicated.
    func duplicateIDs()->[Int]{
        let testArray = table.map{$0.id}.sorted()
        var duplicateIDs:[Int] = []
        for id in testArray{
            let idCount = testArray.filter{$0 == id}.count
            if idCount > 1 {
                duplicateIDs.append(id)
            }
        }
        return duplicateIDs
    }
    
    
